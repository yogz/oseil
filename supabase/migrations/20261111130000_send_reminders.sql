-- The accounts to remind, the oldest update first: a confirmed address, at least one update
-- (snapshot) and the latest one 6 months old or more, the reminder not switched off, and no
-- reminder in the last 6 months (one e-mail per 6 months of absence, never two closer).
create function public.due_reminders() returns table (user_id uuid, email text)
language sql
stable
security definer
set search_path = ''
as $$
  select u.id, u.email::text
  from auth.users u
  join (
    select d.user_id, max(d.created_at) as last_update
    from public.documents d
    where d.kind = 'snapshot'
    group by d.user_id
  ) s on s.user_id = u.id
  left join public.update_reminders r on r.user_id = u.id
  where u.email_confirmed_at is not null
    and u.email is not null
    and u.deleted_at is null
    and s.last_update <= now() - interval '6 months'
    and not coalesce(r.email_off, false)
    and (r.last_sent_at is null or r.last_sent_at <= now() - interval '6 months')
  order by s.last_update, u.id;
$$;

revoke all on function public.due_reminders() from public, anon, authenticated;

-- Notes that a reminder leaves now (creating the row if needed) and returns the account's
-- unsubscribe token. Called before the request: a failure loses a reminder, never sends two.
create function public.mark_reminder_sent(target uuid) returns uuid
language sql
security definer
set search_path = ''
as $$
  insert into public.update_reminders (user_id, last_sent_at)
  values (mark_reminder_sent.target, now())
  on conflict (user_id) do update set last_sent_at = excluded.last_sent_at
  returning unsubscribe_token;
$$;

revoke all on function public.mark_reminder_sent(uuid) from public, anon, authenticated;

-- Sends the reminder to one account, due or not (Nicolas's test e-mail). Returns false, and
-- marks nothing, without the key, without a confirmed address, or when the reminder is off.
create function public.send_reminder(target uuid) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  api_key text;
  address text;
  token uuid;
begin
  -- One send at a time: overlapping runs would each read the same due accounts and both send.
  perform pg_advisory_xact_lock(hashtext('update_reminders_send'));
  select s.decrypted_secret into api_key
  from vault.decrypted_secrets s
  where s.name = 'resend_reminder_key'
  limit 1;
  if api_key is null then
    return false;
  end if;

  select u.email::text into address
  from auth.users u
  left join public.update_reminders r on r.user_id = u.id
  where u.id = send_reminder.target
    and u.email is not null
    and u.email_confirmed_at is not null
    and u.deleted_at is null
    and not coalesce(r.email_off, false);
  if address is null then
    return false;
  end if;

  token := public.mark_reminder_sent(send_reminder.target);
  -- The Bearer key waits in net.http_request_queue until pg_net's worker sends it (pg_net design;
  -- only privileged roles can read that table).
  perform net.http_post(
    url := 'https://api.resend.com/emails',
    body := public.reminder_email(address, token),
    headers := jsonb_build_object('Authorization', 'Bearer ' || api_key, 'Content-Type', 'application/json'),
    timeout_milliseconds := 10000
  );
  return true;
end;
$$;

revoke all on function public.send_reminder(uuid) from public, anon, authenticated;

-- The daily job: at most 20 reminders (Resend's free plan, 100 e-mails a day, is shared with the
-- sign-in e-mails), the oldest update first, the rest on the following days. Marks each account
-- first, then makes one single call to Resend's batch sending. Returns how many were queued.
create function public.send_due_reminders() returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  api_key text;
  emails jsonb := '[]'::jsonb;
  account record;
  token uuid;
begin
  -- One send at a time: overlapping runs would each read the same due accounts and both send.
  perform pg_advisory_xact_lock(hashtext('update_reminders_send'));
  select s.decrypted_secret into api_key
  from vault.decrypted_secrets s
  where s.name = 'resend_reminder_key'
  limit 1;
  if api_key is null then
    return 0;
  end if;

  for account in
    select d.user_id, d.email
    from public.due_reminders() with ordinality as d (user_id, email, n)
    order by d.n
    limit 20
  loop
    token := public.mark_reminder_sent(account.user_id);
    emails := emails || jsonb_build_array(public.reminder_email(account.email, token));
  end loop;

  if jsonb_array_length(emails) = 0 then
    return 0;
  end if;

  -- The Bearer key waits in net.http_request_queue until pg_net's worker sends it (pg_net design;
  -- only privileged roles can read that table).
  perform net.http_post(
    url := 'https://api.resend.com/emails/batch',
    body := emails,
    headers := jsonb_build_object('Authorization', 'Bearer ' || api_key, 'Content-Type', 'application/json'),
    timeout_milliseconds := 30000
  );
  return jsonb_array_length(emails);
end;
$$;

revoke all on function public.send_due_reminders() from public, anon, authenticated;
